import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { TOOL_FEATURES } from '../src/components/tools/toolCatalog'
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('anveshak-onboarding-complete', 'true')
    localStorage.setItem('anveshak-tour-done', 'yes')
    localStorage.setItem('home-tour-seen', 'true')
    localStorage.setItem('pref-workspace-mode', 'learn')
    localStorage.setItem('pref-motion', 'reduced')
  })
})

test('all 50 features open and the browser filters tools', async ({ page }) => {
  test.setTimeout(90_000)
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  for (const feature of TOOL_FEATURES) {
    await page.goto(`/#/tools?feature=${feature.id}`)
    await expect(page.getByRole('heading', { name: feature.title, exact: true }).first()).toBeVisible()
  }
  await page.getByText('Browse all 50 features', { exact: true }).click()
  if (!(await page.getByLabel('Search tool features').isVisible())) await page.getByText('Browse all 50 features', { exact: true }).click()
  await page.getByLabel('Search tool features').fill('bootstrap')
  await expect(page.getByRole('navigation', { name: 'Tool features' }).getByRole('button', { name: /Bootstrap analysis/ })).toBeVisible()
  const count = TOOL_FEATURES.filter(f => `${f.title} ${f.description}`.toLowerCase().includes('bootstrap')).length
  await expect(page.getByText(`${count} of 50 features`)).toBeVisible()
  expect(errors).toEqual([])
})

