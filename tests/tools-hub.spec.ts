test('resampling, corrections, workflows, history and reproducible reports work', async ({ page }) => {
  await page.goto('/#/tools?feature=bootstrap')
  await page.getByLabel('Numeric column').selectOption('math')
  await page.getByLabel('Random seed').fill('123')
  await page.getByRole('button', { name: 'Calculate results' }).click()
  await expect(page.getByRole('table', { name: '95% mean intervals' })).toBeVisible()
  await page.goto('/#/tools?feature=multiplicity')
  await page.getByLabel('P-values (comma or space separated)').fill('0.01,0.04,0.03,0.2')
  await page.getByRole('button', { name: 'Calculate results' }).click()
  await expect(page.getByRole('table', { name: 'Adjusted p-values' })).toBeVisible()
  await page.goto('/#/tools?feature=workflow')
  await page.getByLabel('Workflow numeric column').selectOption('math')
  await page.getByRole('button', { name: 'Run workflow', exact: true }).click()
  await expect(page.getByRole('table', { name: /Step 2: mean interval/ })).toBeVisible()
  const workflowDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export workflow report' }).click()
  expect((await workflowDownload).suggestedFilename()).toBe('workflow-report.txt')
  await page.goto('/#/tools?feature=history')
  await page.getByLabel('Saved analysis run').selectOption({ index: 2 })
  await page.getByRole('button', { name: 'Resume saved settings' }).click()
  await expect(page.getByLabel('Random seed')).toHaveValue('123')
  await expect(page.getByLabel('Numeric column')).toHaveValue('math')
  await page.goto('/#/tools?feature=report')
  await page.getByLabel('Report notes').fill('Reviewed analysis')
  const reportDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export reproducible JSON' }).click()
  const download = await reportDownload
  const bundle = JSON.parse(await readFile((await download.path())!, 'utf8'))
  expect(bundle.notes).toBe('Reviewed analysis')
  expect(bundle.runs[0].fingerprint).toMatch(/^fnv1a-/)
  expect(bundle.runs[0].options.column).toBe('math')
})

