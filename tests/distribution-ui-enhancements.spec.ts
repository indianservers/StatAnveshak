import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('anveshak-onboarding-complete', 'true')
    localStorage.setItem('anveshak-tour-done', 'yes')
    localStorage.setItem('pref-workspace-mode', 'learn')
  })
})

test('appearance, accessibility and motion preferences persist', async ({ page }, info) => {
  await page.goto('/#/distributions/normal?tab=viz')
  await page.getByText('Appearance & chart settings', { exact: false }).click()
  await page.getByLabel('App theme', { exact: true }).selectOption('dark')
  await page.getByLabel('Studio palette').selectOption('ocean')
  await page.getByLabel('Layout density').selectOption('compact')
  await page.getByLabel('Animation speed').selectOption('slow')
  await page.getByRole('button', { name: 'Larger lesson text' }).click()
  await page.getByRole('button', { name: 'High contrast charts & text' }).click()
  await page.getByRole('button', { name: 'Pause motion' }).click()
  const studio = page.locator('.dist-studio')
  await expect(studio).toHaveAttribute('data-motion', 'reduced')
  await expect(studio).toHaveAttribute('data-contrast', 'true')
  expect(await studio.evaluate(el => getComputedStyle(el).getPropertyValue('--dist-line').trim())).toBe('#c7d2fe')
  await page.screenshot({ path: `tmp/distributions-dark-${info.project.name}.png` })
  await page.reload()
  await expect(studio).toHaveAttribute('data-palette', 'ocean')
  await expect(studio).toHaveAttribute('data-density', 'compact')
  await expect(studio).toHaveAttribute('data-readable', 'true')
  await page.getByRole('button', { name: 'Resume motion' }).click()
  await expect(studio).toHaveAttribute('data-motion', 'full')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(studio).toHaveAttribute('data-motion', 'reduced')
  await page.getByText('Appearance & chart settings', { exact: false }).click()
  await expect(page.getByRole('button', { name: 'Replay illustrations' })).toBeDisabled()
})

test('distribution browser search, favorites, recent history and focus work', async ({ page }, info) => {
  await page.goto('/#/distributions/normal')
  await page.getByRole('button', { name: /Add Normal .*distribution favorites/ }).click()
  if (info.project.name === 'mobile') await page.getByRole('button', { name: 'Browse & search distributions' }).click()
  await page.getByLabel('Find a distribution').fill('not-a-distribution')
  await expect(page.getByText(/No matches/)).toBeVisible()
  await page.getByLabel('Find a distribution').fill('')
  await page.getByRole('button', { name: 'Favorites only' }).click()
  await expect(page.getByText('1 of 32 distributions')).toBeVisible()
  await page.getByRole('button', { name: 'Show all distributions' }).click()
  await page.getByLabel('Find a distribution').fill('poisson')
  await page.getByRole('button', { name: 'Poisson', exact: true }).filter({ visible: true }).click()
  await expect(page).toHaveURL(/distributions\/poisson/)
  await page.getByRole('button', { name: 'Focus mode', exact: true }).click()
  await expect(page.getByRole('complementary', { name: 'Distribution browser' })).toBeHidden()
  await page.getByLabel('Distribution in focus').selectOption('beta')
  await expect(page).toHaveURL(/distributions\/beta/)
  await page.getByRole('button', { name: 'Exit focus mode' }).click()
})

test('keyboard tabs, chart values, modal, two tails and SVG download work', async ({ page }, info) => {
  await page.goto('/#/distributions/normal')
  await page.getByRole('tab', { name: 'Learn', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'Visualization' })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: 'Formulas', exact: true }).click()
  await page.goBack()
  await expect(page.getByRole('tab', { name: 'Visualization' })).toHaveAttribute('aria-selected', 'true')
  const explorer = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Probability explorer', exact: true }) })
  await explorer.getByRole('button', { name: 'Two tails', exact: true }).click()
  await expect(explorer.getByText('■ Selected tails')).toBeVisible()
  await expect(explorer.locator('svg').first().locator('path[fill="var(--dist-selection)"]')).toHaveCount(2)
  await explorer.getByText('Inspect values & data', { exact: true }).click()
  await explorer.getByLabel('Chart point').focus()
  await page.keyboard.press('ArrowRight')
  await expect(explorer.locator('.dist-chart-tooltip')).toBeVisible()
  await expect(explorer.getByRole('table')).toBeVisible()
  await expect(explorer.getByRole('button', { name: 'Two tails', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const downloadPromise = page.waitForEvent('download')
  await explorer.getByRole('button', { name: 'Save SVG', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('normal-density.svg')
  const exported = await readFile((await download.path())!, 'utf8')
  expect(exported).toContain('xmlns="http://www.w3.org/2000/svg"')
  expect(exported).not.toContain('var(--dist-')
  await expect(explorer.getByRole('button', { name: 'Two tails', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await explorer.getByRole('button', { name: 'Expand chart', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog').locator('path[fill="var(--dist-selection)"]')).toHaveCount(2)
  await page.screenshot({ path: `tmp/distributions-expanded-${info.project.name}.png` })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeHidden()
  expect(await page.locator('.dist-studio').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
  await page.goto('/#/distributions/normal')
  await page.getByRole('button', { name: 'Pause motion' }).click()
  await page.getByRole('region', { name: 'Distribution appearance' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: `tmp/distributions-default-${info.project.name}.png` })
})

test('singular endpoint curves remain finite and all theme choices work', async ({ page }) => {
  await page.goto('/#/distributions/beta?tab=viz')
  await page.getByRole('spinbutton', { name: 'α', exact: true }).fill('0.5')
  await page.getByRole('spinbutton', { name: 'β', exact: true }).fill('0.5')
  expect(await page.locator('.dist-chart-frame svg').evaluateAll(nodes => nodes.every(node => !/NaN|Infinity/.test(node.innerHTML)))).toBe(true)
  await page.getByText('Appearance & chart settings', { exact: false }).click()
  for (const theme of ['light', 'dark', 'midnight', 'forest', 'rose', 'sepia']) {
    await page.getByLabel('App theme', { exact: true }).selectOption(theme)
    await expect(page.locator(`.theme-${theme}`).first()).toBeVisible()
  }
})
