import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
const labs = ['one-way-anova', 'anova-table', 'post-hoc-comparisons', 'two-way-anova', 'repeated-measures-anova', 'anova-assumptions']
const groups = 'group,value\nA,10\nA,12\nA,14\nB,15\nB,18\nB,20\nC,22\nC,23\nC,27\nA,\n'
const factorial = 'a,b,value\nA,X,10\nA,X,12\nA,Y,15\nA,Y,17\nB,X,13\nB,X,15\nB,Y,25\nB,Y,27'
const repeated = 'subject,condition,value\ns1,Before,10\ns1,After,13\ns2,Before,15\ns2,After,17\ns3,Before,12\ns3,After,16\ns4,Before,17\ns4,After,18\ns5,Before,20'
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('anveshak-onboarding-complete', 'true')
    localStorage.setItem('anveshak-tour-done', 'yes')
    localStorage.setItem('home-tour-seen', 'true')
    localStorage.setItem('pref-workspace-mode', 'learn')
    localStorage.setItem('pref-motion', 'reduced')
  })
})
test('ANOVA landing page leads into the guided data workflow', async ({ page }) => {
  await page.goto('/#/statistics/anova')
  await expect(page.getByRole('heading', { name: 'Learn with your own data in every lab' })).toBeVisible()
  await page.getByRole('link', { name: 'Start the guided one-way lab' }).click()
  await expect(page.getByRole('region', { name: 'Guided data and analysis tools' })).toBeVisible()
})
for (const slug of labs) test(`${slug}: map real data, guide, calculate, and roundtrip session`, async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`/#/statistics/anova/${slug}`)
  const tools = page.getByRole('region', { name: 'Guided data and analysis tools' })
  await expect(tools).toBeVisible()
  await tools.getByRole('button', { name: '2 · Prepare the data' }).click()
  await tools.getByLabel('Paste CSV or tab-separated data').fill(slug === 'two-way-anova' ? factorial : slug === 'repeated-measures-anova' ? repeated : groups)
  await tools.getByRole('button', { name: 'Read pasted table' }).click()
  await tools.getByRole('combobox', { name: slug === 'repeated-measures-anova' ? 'Map condition' : 'Map factor A', exact: true }).selectOption(slug === 'two-way-anova' ? 'a' : slug === 'repeated-measures-anova' ? 'condition' : 'group')
  await tools.getByRole('combobox', { name: 'Map numeric outcome' }).selectOption('value')
  if (slug === 'two-way-anova') await tools.getByRole('combobox', { name: 'Map factor B', exact: true }).selectOption('b')
  if (slug === 'repeated-measures-anova') await tools.getByRole('combobox', { name: 'Map subject ID' }).selectOption('subject')
  await tools.getByRole('button', { name: 'Apply mapped observations' }).click()
  await expect(tools.getByText(/Applied (8|9) observations/).last()).toBeVisible()
  await tools.getByRole('button', { name: '4 · Read the result' }).click()
  await expect(tools.getByRole('heading', { name: /One-way ·|ANOVA table ·|Post-hoc ·|Two-way ·|Repeated measures ·|Assumptions ·/ })).toBeVisible()
  await tools.getByRole('combobox', { name: 'Learning tools alpha' }).selectOption('0.01')
  await expect(tools.getByRole('combobox', { name: 'Learning tools alpha' })).toHaveValue('0.01')
  const pending = page.waitForEvent('download')
  await tools.getByRole('button', { name: 'Export lab session', exact: true }).click()
  const downloaded = await pending, path = await downloaded.path()
  expect(downloaded.suggestedFilename()).toBe(`${slug}-session.json`)
  const session = JSON.parse(await readFile(path!, 'utf8'))
  expect(session.lab).toBe(slug)
  expect(session.alpha).toBe(.01)
  expect(session.rows.length).toBe(slug === 'two-way-anova' ? 8 : 9)
  await tools.getByRole('button', { name: '2 · Prepare the data' }).click()
  await tools.getByLabel('Restore lab session').setInputFiles({ name: 'saved-session.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(session)) })
  await expect(tools.getByText(/Restored session: saved-session.json/).last()).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
