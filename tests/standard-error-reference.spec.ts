import { expect, test } from '@playwright/test'

test('reference layout keeps guide, modes and simulation controls working', async ({ page }, info) => {
  if (info.project.name === 'chromium') await page.setViewportSize({ width: 1536, height: 1024 })
  await page.addInitScript(() => {
    localStorage.setItem('anveshak-onboarding-complete', 'true')
    localStorage.setItem('anveshak-tour-done', 'yes')
    localStorage.setItem('home-tour-seen', 'true')
    localStorage.setItem('pref-workspace-mode', 'learn')
    localStorage.setItem('pref-motion', 'reduced')
  })
  await page.goto('/#/statistics/sampling-distributions-clt/standard-error')
  await expect(page.getByRole('heading', { name: 'Standard Error', exact: true })).toBeVisible()
  const controls = page.getByRole('complementary', { name: 'Simulation controls' })
  await expect(controls.getByRole('slider', { name: 'Sample size (n)', exact: true })).toHaveValue('50')
  await page.screenshot({ path: `test-results/standard-error-reference-${info.project.name}.png`, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await controls.getByRole('button', { name: '200', exact: true }).click()
  await expect(page.locator('.se-metric').last()).toContainText('0.71')
  const summary = page.locator('.se-summary')
  const before = await summary.innerText()
  await controls.getByRole('button', { name: 'Draw samples' }).click()
  await expect(summary).not.toHaveText(before)
  await controls.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(controls.getByRole('slider', { name: 'Sample size (n)', exact: true })).toHaveValue('50')
  await page.getByRole('button', { name: 'Guide', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog').getByRole('heading', { name: 'Required inputs', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close guide' }).click()
  const modes = page.getByRole('navigation', { name: 'Lab modes', exact: true })
  await modes.getByRole('button', { name: 'Learn', exact: true }).click()
  await expect(page.getByText('Standard error is not standard deviation', { exact: true })).toBeVisible()
  await modes.getByRole('button', { name: 'Explore', exact: true }).click()
  await expect(controls).toBeVisible()
})

test('shared header keeps navigation and workspace settings accessible', async ({ page }, info) => {
  if (info.project.name === 'chromium') await page.setViewportSize({ width: 1536, height: 1024 })
  await page.addInitScript(() => {
    localStorage.setItem('anveshak-onboarding-complete', 'true')
    localStorage.setItem('anveshak-tour-done', 'yes')
    localStorage.setItem('pref-workspace-mode', 'learn')
  })
  await page.goto('/#/statistics/sampling-distributions-clt/standard-error')
  const mainNav = page.getByRole('navigation', { name: 'Main', exact: true })
  if (info.project.name === 'mobile') await mainNav.getByRole('button', { name: 'Menu', exact: true }).click()
  await mainNav.getByRole('button', { name: 'Data', exact: true }).filter({ visible: true }).click()
  await mainNav.getByRole('link', { name: /Upload Data/ }).filter({ visible: true }).click()
  await expect(page.getByRole('heading', { name: 'Upload Data', exact: true })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Page breadcrumb', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'More workspace controls', exact: true }).click()
  await page.getByRole('button', { name: 'Keyboard shortcuts', exact: true }).filter({ visible: true }).click()
  await expect(page.getByText('Keyboard Shortcuts', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
