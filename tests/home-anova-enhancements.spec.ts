import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('anveshak-onboarding-complete', 'true')
    localStorage.setItem('anveshak-tour-done', 'yes')
    localStorage.setItem('home-tour-seen', 'true')
    localStorage.setItem('pref-workspace-mode', 'learn')
    localStorage.setItem('pref-motion', 'reduced')
  })
})

const csv = 'group,score\nA,10\nA,12\nA,14\nB,20\nB,22\nB,24\nC,30\nC,32\nC,34\nC,\n,15\n'

test('home starts with the hero and cards without workspace panels', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('home-view', 'advanced'))
  await page.goto('/#/')
  await expect(page.getByRole('heading', { name: 'Statistics & Probability' })).toBeVisible()
  await expect(page.locator('main.home-screen > div > section').first()).toHaveAttribute('aria-labelledby', 'home-hero-heading')
  await expect(page.getByRole('searchbox', { name: /Find your next step/ })).toHaveCount(0)
  await expect(page.getByRole('navigation', { name: 'Home sections', exact: true })).toHaveCount(0)
  await expect(page.locator('#home-workspace')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Probability & Statistics Studios', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
test('home imports and persists a dataset for preview', async ({ page }) => {
  await page.goto('/#/')
  await page.getByLabel('Upload dataset from home').setInputFiles({ name: 'anova-home.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
  await expect(page).toHaveURL(/#\/data\/preview/)
  await expect(page.getByRole('heading', { name: 'anova-home', exact: true })).toBeVisible()
  await page.goto('/#/')
  await expect(page.getByRole('heading', { name: 'Statistics & Probability' })).toBeVisible()
})

test('ANOVA imports, validates, edits, undoes, resamples, snapshots, and exports', async ({ page }) => {
  await page.goto('/#/statistics/anova/one-way-anova')
  await expect(page.getByRole('heading', { name: 'One-Way ANOVA', exact: true })).toBeVisible()
  await page.screenshot({ path: `tmp/enhancements-anova-top-${test.info().project.name}.png` })
  await page.getByLabel('Import ANOVA data').setInputFiles({ name: 'groups.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
  await page.getByRole('combobox', { name: 'Group column', exact: true }).selectOption('group')
  await page.getByRole('combobox', { name: 'Outcome column', exact: true }).selectOption('score')
  await page.getByRole('button', { name: 'Analyze mapped data' }).click()
  await expect(page.getByText('Loaded 9 observations. Excluded 2 rows with missing groups or nonnumeric outcomes.').first()).toBeVisible()
  const outcome = page.getByRole('spinbutton', { name: 'Outcome for import-1', exact: true })
  await outcome.fill('')
  await outcome.press('Enter')
  await expect(outcome).toHaveValue('10')
  await outcome.fill('18')
  await outcome.press('Enter')
  await expect(outcome).toHaveValue('18')
  await page.getByRole('button', { name: 'Undo data change' }).click()
  await expect(outcome).toHaveValue('10')
  await page.getByRole('button', { name: 'Redo data change' }).click()
  await expect(outcome).toHaveValue('18')
  await page.getByRole('combobox', { name: 'Significance level α' }).selectOption('0.01')
  await expect(page.getByText('99% t intervals', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Save snapshot', exact: true }).click()
  await expect(page.getByText('Compare saved results with current data')).toBeVisible()
  await page.getByRole('button', { name: 'Resample', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Outcome for import-1', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Restore snapshot', exact: true }).click()
  await expect(outcome).toHaveValue('18')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download data CSV', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('anova-data.csv')
  await page.getByText('Assumption diagnostics & F distribution', { exact: true }).click()
  await expect(page.getByRole('img', { name: 'F distribution with observed F and critical value' })).toBeVisible()
  await page.getByText('Pairwise comparisons on these same data', { exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Multiple-comparison method' })).toBeVisible()
  await page.screenshot({ path: `tmp/enhancements-anova-${test.info().project.name}.png` })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Confirm reset', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Keep working', exact: true }).click()
  await expect(outcome).toHaveValue('18')
})

test('ANOVA completion is explicit and notes survive revisiting', async ({ page }) => {
  await page.goto('/#/statistics/anova/one-way-anova')
  await expect(page.getByRole('button', { name: 'Mark lab complete', exact: true })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('anveshak-anova-studio') ?? '{}').completed ?? [])).toEqual([])
  await page.getByRole('textbox', { name: 'Lab notes', exact: true }).fill('Separating means raises F relative to within-group variation.')
  await page.getByRole('button', { name: 'Save notes', exact: true }).click()
  await page.getByRole('button', { name: 'Mark lab complete', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Completed — mark incomplete', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Lab notes', exact: true })).toHaveValue('Separating means raises F relative to within-group variation.')
  await expect(page.getByRole('button', { name: 'Completed — mark incomplete', exact: true })).toBeVisible()
})

