test('ANOVA dark mode and mobile lab navigation remain readable and usable', async ({ page, isMobile }) => {
  await page.addInitScript(() => localStorage.setItem('pref-theme', 'dark'))
  await page.goto('/#/statistics/anova/one-way-anova')
  await expect(page.getByRole('heading', { name: 'One-Way ANOVA', exact: true })).toBeVisible()
  if (isMobile) {
    const toggle = page.getByRole('button', { name: /Show labs & progress/ })
    await expect(toggle).toBeVisible()
    await expect(page.getByRole('navigation', { name: 'ANOVA labs', exact: true })).toBeHidden()
    await toggle.click()
    await expect(page.getByRole('navigation', { name: 'ANOVA labs', exact: true })).toBeVisible()
    await page.getByRole('button', { name: /Hide labs & progress/ }).click()
    await expect(toggle).toHaveCSS('background-color', 'rgb(30, 41, 59)')
  }
  await page.screenshot({ path: `tmp/enhancements-anova-dark-${test.info().project.name}.png` })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
